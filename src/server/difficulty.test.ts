const git = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, encoding: 'utf8', env: { ...process.env, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_NOSYSTEM: '1' } });

/** A local origin with old source by two other people, plus assets, a lockfile and vendored code. */
function makeOrigin(root: string): { dir: string; head: string } {
  const dir = join(root, 'origin');
  mkdirSync(join(dir, 'src'), { recursive: true });
  mkdirSync(join(dir, 'assets'), { recursive: true });
  mkdirSync(join(dir, 'vendor'), { recursive: true });
  git(dir, 'init', '-q', '-b', 'main');
  git(dir, 'config', 'uploadpack.allowFilter', 'true');
  git(dir, 'config', 'uploadpack.allowAnySHA1InWant', 'true');
  const commit = (who: string, when: string, msg: string) =>
    execFileSync('git', ['-c', `user.name=${who}`, '-c', `user.email=${who}@example.com`, 'commit', '-qm', msg], { cwd: dir, env: { ...process.env, GIT_AUTHOR_DATE: when, GIT_COMMITTER_DATE: when, GIT_CONFIG_GLOBAL: '/dev/null' } });
  const lines = Array.from({ length: 600 }, (_, i) => `export const value${i} = compute(${i}, options.step);`);
  writeFileSync(join(dir, 'src/core.ts'), `${lines.slice(0, 300).join('\n')}\n`);
  writeFileSync(join(dir, 'assets/logo.png'), Buffer.alloc(40_000, 7));
  writeFileSync(join(dir, 'pnpm-lock.yaml'), 'lockfileVersion: 9\n');
  writeFileSync(join(dir, 'vendor/lib.js'), 'var lib = make(1);\n');
  git(dir, 'add', '-A');
  commit('olga', '2021-02-01T10:00:00Z', 'core');
  writeFileSync(join(dir, 'src/core.ts'), `${lines.join('\n')}\n`);
  writeFileSync(join(dir, 'assets/logo.png'), Buffer.alloc(40_000, 9));
  git(dir, 'add', '-A');
  commit('piet', '2022-06-01T10:00:00Z', 'more core');
  return { dir, head: git(dir, 'rev-parse', 'HEAD').trim() };
}

describe('the local mirror', () => {
  let root: string;
  let origin: { dir: string; head: string };
  beforeAll(() => {
    root = mkdtempSync(join(tmpdir(), 'mirror-test-'));
    origin = makeOrigin(root);
  });
  afterAll(() => rmSync(root, { recursive: true, force: true }));
  let mirrorDir: string;
  beforeEach(() => {
    mirrorDir = join(root, `mirrors-${Math.random().toString(36).slice(2)}`);
  });
  const mirrorOf = (opts: Partial<ConstructorParameters<typeof Mirror>[0]> = {}) => new Mirror({ dir: mirrorDir, remote: () => `file://${origin.dir}`, clock: () => FIXTURE_NOW, ...opts });

  it('validates names and reads only source paths', () => {
    expect(validRepoName('vitejs/vite')).toBe(true);
    expect(validRepoName('a/..')).toBe(false);
    expect(validRepoName('-x/y')).toBe(false);
    expect(validRepoName('a/b c')).toBe(false);
    expect(validRepoName('a/b;rm')).toBe(false);
    expect(readablePath('src/core.ts')).toBe(true);
    for (const p of ['assets/logo.png', 'pnpm-lock.yaml', 'vendor/lib.js', 'dist/app.js', '../etc/passwd.ts', '-x.ts', 'src/a.min.js', 'README.md']) expect(readablePath(p)).toBe(false);
  });

  it('blames a source file from a bare partial clone holding no other file’s contents', async () => {
    const mirror = mirrorOf();
    const facts = await mirror.facts('olga/core', origin.head, ['src/core.ts', 'assets/logo.png', 'pnpm-lock.yaml', 'vendor/lib.js'], 50);
    expect([...facts.keys()]).toEqual(['src/core.ts']);
    const core = facts.get('src/core.ts')!;
    expect(core.blame[0]).toMatchObject({ start: 1, end: 300, author: 'email:olga@example.com' });
    expect(core.blame[1]).toMatchObject({ start: 301, end: 600, author: 'email:piet@example.com' });
    expect(core.history.total).toBe(2);
    // Bare, and only the source file's blobs are stored.
    const dir = mirror.pathOf('olga/core');
    expect(git(dir, 'rev-parse', '--is-bare-repository').trim()).toBe('true');
    const blobs = git(dir, 'cat-file', '--batch-all-objects', '--batch-check').split('\n').filter((l) => / blob /.test(l));
    expect(blobs).toHaveLength(2);
    const sizes = blobs.map((l) => Number(l.split(' ')[2]));
    expect(Math.max(...sizes)).toBeLessThan(40_000);
  });

  it('respects the 50 MB cap: never clones a bigger repository, and drops a mirror that outgrows it', async () => {
    const big = mirrorOf();
    expect((await big.facts('olga/core', origin.head, ['src/core.ts'], 60 * 1024)).size).toBe(0);
    expect(big.stats.clones).toBe(0);
    const tiny = mirrorOf({ maxBytes: 4_000 });
    expect((await tiny.facts('olga/core', origin.head, ['src/core.ts'], 1)).size).toBe(0);
    expect(tiny.stats.dropped).toBe(1);
    expect(tiny.sizeOf('olga/core')).toBe(0);
  });

  it('prunes mirrors untouched for 14 days', async () => {
    const mirror = mirrorOf();
    await mirror.facts('olga/core', origin.head, ['src/core.ts'], 50);
    expect(mirror.prune(FIXTURE_NOW + 13 * 86_400_000)).toEqual([]);
    const marker = join(mirror.pathOf('olga/core'), 'pushfront-used');
    const old = new Date(FIXTURE_NOW - 15 * 86_400_000);
    utimesSync(marker, old, old);
    expect(mirror.prune(FIXTURE_NOW)).toEqual(['olga__core.git']);
  });

  it('is the fallback when GraphQL fails, and neutral is the last resort', async () => {
    const mirror = mirrorOf();
    const t = setup({ mirror });
    const repo = 'olga/core';
    t.github.setRepoFacts({ fullName: repo, fork: false, createdAt: Date.parse('2020-01-01T00:00:00Z'), stars: 40, forks: 3, sizeKb: 50 }, { TypeScript: 30_000 });
    t.github.graphqlTrouble = 'down';
    const removed = Array.from({ length: 6 }, (_, i) => `export const value${100 + i} = compute(${100 + i}, options.step);`);
    const added = Array.from({ length: 6 }, (_, i) => `export const value${100 + i} = computeSafely(${100 + i}, options.step, limits);`);
    const patch = ['@@ -100,8 +100,8 @@', ` export const value99 = compute(99, options.step);`, ...removed.map((l) => `-${l}`), ...added.map((l) => `+${l}`), ` export const value106 = compute(106, options.step);`].join('\n');
    const file = { filename: 'src/core.ts', status: 'modified', additions: 6, deletions: 6, patch };
    const c = await t.context.forDiff(repo, { base: origin.head, files: [file] }, pusherOf(MAINTAINER.id, MAINTAINER.login, ['mara@example.com']));
    const core = c!.files['src/core.ts']!;
    expect(core.source).toBe('mirror');
    expect(core.others).toEqual([101, 102, 103, 104, 105, 106]);
    expect(core.mMilli).toBeGreaterThan(1500);
    expect(t.context.stats.mirrorFiles).toBe(1);

    // With no mirror (MIRROR_DIR unset), the same failure is neutral.
    const none = setup();
    none.github.setRepoFacts({ fullName: repo, fork: false, createdAt: 0, stars: 40, forks: 3, sizeKb: 50 }, { TypeScript: 30_000 });
    none.github.graphqlTrouble = 'down';
    expect(await none.context.forDiff(repo, { base: origin.head, files: [file] }, pusherOf(MAINTAINER.id, MAINTAINER.login))).toBeNull();
  });
});

