beforeAll(() => loadAllGrammars());

function setup(opts: { mirror?: Mirror | null } = {}) {
  const github = new FakeGithub();
  const store = new Store(openDb(':memory:'));
  store.upsertUser({ id: MAINTAINER.id, nodeId: 'U', login: MAINTAINER.login, avatarUrl: '', createdAtGithub: 0, joinedAt: 0, bot: false });
  let now = FIXTURE_NOW;
  const clock = () => now;
  const context = new DifficultyContext({ github, clock, mirror: opts.mirror ?? null, timeoutMs: 50 });
  const reports: PushReport[] = [];
  const ingest = (repo: string, before: string, head: string) =>
    ingestPush({ store, github, clock, onPush: (r) => reports.push(r), context }, store.user(MAINTAINER.id)!, { repo, ref: 'refs/heads/main', before, head, at: now });
  return { github, store, context, reports, ingest, advance: (ms: number) => (now += ms) };
}

describe('difficulty context over GraphQL', () => {
  it('reads blame and history for the most changed source files in one query, before the push is recorded', async () => {
    const t = setup();
    installVite(t.github);
    const r = await t.ingest(VITE_REPO, VITE_BASE, VITE_HEAD);
    expect(r).not.toBeNull();
    expect(r!.lines[Cat.Code]).toBe(5);
    // css.ts 2 lines × 2.2, build.ts and asset.ts 1 × 2.2 each, sourcemap.ts 1 × 1.6: 10.4, credited in whole lines.
    expect(r!.bonus).toBe(10);
    expect(t.github.calls.graphql).toBe(1);
    expect(Object.keys(t.github.graphqlAsked[0]!).filter((k) => /^p\d$/.test(k))).toHaveLength(4);
    // The bonus is part of what was recorded.
    expect(JSON.parse(JSON.stringify(r)).bonus).toBe(10);
  });

  it('never fetches context for assets, lockfiles, vendored, generated or added files', async () => {
    const t = setup();
    installVite(t.github);
    const extra = [
      { filename: 'docs/logo.png', status: 'modified', additions: 0, deletions: 0, patch: null },
      { filename: 'pnpm-lock.yaml', status: 'modified', additions: 10, deletions: 10, patch: '@@ -1,1 +1,1 @@\n-a: 1\n+a: 2' },
      { filename: 'vendor/lib.js', status: 'modified', additions: 1, deletions: 1, patch: '@@ -1,1 +1,1 @@\n-var a = b(c);\n+var a = b(d);' },
      { filename: 'packages/vite/src/client/env.generated.ts', status: 'modified', additions: 1, deletions: 1, patch: '@@ -1,1 +1,1 @@\n-// @generated\n+// @generated by x' },
      { filename: 'packages/vite/src/node/new.ts', status: 'added', additions: 1, deletions: 0, patch: '@@ -0,0 +1,1 @@\n+export const z = make(y);' },
    ];
    const files = [...viteFiles().map((f) => f.file), ...extra];
    const c = await t.context.forDiff(VITE_REPO, { base: VITE_BASE, files }, pusherOf(MAINTAINER.id, MAINTAINER.login));
    const asked = Object.entries(t.github.graphqlAsked[0]!).filter(([k]) => /^p\d$/.test(k)).map(([, v]) => v);
    expect(asked.sort()).toEqual(viteFiles().map((f) => f.file.filename).sort());
    expect(Object.keys(c!.files).sort()).toEqual(asked);
  });

  it('caches the repository’s REST facts per repository per day', async () => {
    const t = setup();
    const { files } = installVite(t.github);
    const pusher = pusherOf(MAINTAINER.id, MAINTAINER.login);
    await t.context.forDiff(VITE_REPO, { base: VITE_BASE, files }, pusher);
    await t.context.forDiff(VITE_REPO, { base: VITE_BASE, files }, pusher);
    expect(t.github.calls.repoFacts).toBe(1);
    expect(t.github.calls.languages).toBe(1);
    t.advance(86_400_000);
    await t.context.forDiff(VITE_REPO, { base: VITE_BASE, files }, pusher);
    expect(t.github.calls.repoFacts).toBe(2);
  });

  it('spends no GraphQL on a greenfield push, and credits it 1×', async () => {
    const t = setup();
    installGreenfield(t.github);
    const r = await t.ingest('mara/fresh-app', 'd'.repeat(40), 'e'.repeat(40));
    expect(r!.lines[Cat.Code]).toBe(500);
    expect(r!.bonus ?? 0).toBe(0);
    expect(t.github.calls.graphql).toBe(0);
  });

  it('gives the pusher’s own old lines no bonus', async () => {
    const t = setup();
    installVite(t.github, { pusherOwnsChangedLines: true });
    const r = await t.ingest(VITE_REPO, VITE_BASE, VITE_HEAD);
    expect(r!.lines[Cat.Code]).toBe(5);
    expect(r!.bonus ?? 0).toBe(0);
  });

  it('holds a repository without stars, forks and independent contributors to ×1.5, and says why', async () => {
    const t = setup();
    const { files } = installVite(t.github);
    t.github.setRepoFacts({ ...VITE_FACTS, stars: 1, forks: 0 }, { TypeScript: 3_000_000 });
    const c = await t.context.forDiff(VITE_REPO, { base: VITE_BASE, files }, pusherOf(MAINTAINER.id, MAINTAINER.login));
    const css = c!.files['packages/vite/src/node/plugins/css.ts']!;
    expect(css.rawMilli).toBe(3200);
    expect(css.mMilli).toBe(GATE_CAP * 1000);
    expect(css.gate.reason).toBe('fewer than 5 stars and 2 forks');
  });

  it('a new repository with forged old history and sockpuppet authors earns little', async () => {
    const t = setup();
    const repo = 'mara/legacy-looking';
    const base = 'f'.repeat(40);
    t.github.setRepoFacts({ fullName: repo, fork: false, createdAt: FIXTURE_NOW - 3 * 86_400_000, stars: 0, forks: 0, sizeKb: 900 }, { TypeScript: 900_000 });
    // 100 "authors" whose accounts were made this week, commits backdated to 2015.
    const puppets = Array.from({ length: 100 }, (_, i) => ({ id: 9000 + i, createdAt: new Date(FIXTURE_NOW - 2 * 86_400_000).toISOString() }));
    const file = viteFiles()[0]!.file;
    t.github.setFileFacts(repo, base, file.filename, { blame: blameOf(4000, puppets, ['2015-01-01T00:00:00Z']), history: { total: 600, commits: puppets.map((a) => ({ date: '2015-01-01T00:00:00Z', author: a })) } });
    const c = await t.context.forDiff(repo, { base, files: [file] }, pusherOf(MAINTAINER.id, MAINTAINER.login));
    const f = c!.files[file.filename]!;
    expect(f.authorsOthers).toBe(0);
    expect(f.medianAgeDays).toBeLessThanOrEqual(3);
    expect(f.gate.passed).toBe(false);
    // Only lines and commits remain, and the gate holds those to ×1.5.
    expect(f.mMilli).toBeLessThanOrEqual(1500);
  });

  it('retries one file per query when the batch fails, then falls back to neutral', async () => {
    const t = setup();
    installVite(t.github);
    t.github.graphqlTrouble = 'batch';
    const r = await t.ingest(VITE_REPO, VITE_BASE, VITE_HEAD);
    expect(t.github.calls.graphql).toBe(5);
    expect(r!.bonus).toBe(10);

    const down = setup();
    installVite(down.github);
    down.github.graphqlTrouble = 'down';
    const n = await down.ingest(VITE_REPO, VITE_BASE, VITE_HEAD);
    expect(n!.lines[Cat.Code]).toBe(5);
    expect(n!.bonus ?? 0).toBe(0);
    expect(down.context.stats.neutralFiles).toBe(4);
  });

  it('gives up on a query past its timeout', async () => {
    const t = setup();
    installVite(t.github);
    t.github.graphqlTrouble = 'slow';
    const started = Date.now();
    const r = await t.ingest(VITE_REPO, VITE_BASE, VITE_HEAD);
    expect(r!.bonus ?? 0).toBe(0);
    expect(Date.now() - started).toBeLessThan(2_000);
  });

  it('keeps file paths out of the query text', () => {
    expect(contextQuery(2)).not.toMatch(/css\.ts/);
    expect(contextQuery(2)).toMatch(/\$p1: String!/);
  });
});

