// Vendors the tree-sitter grammars (`.wasm`) that rules/complexity.ts parses with into
// assets/grammars/, and records where each came from: package, version, sha256 and license.
//
// The grammar packages are not dependencies: they ship native bindings with install scripts
// (node-gyp-build), and the Kotlin one pulls in npm-check-updates at runtime. Only their published
// `.wasm` files are needed, so those are checked in and `web-tree-sitter` (pinned) loads them.
//
//   pnpm tsx scripts/vendor-grammars.ts            fetch each pinned package with `npm pack` (no install
//                                                  scripts run), extract its .wasm and LICENSE, write the manifest
//   pnpm tsx scripts/vendor-grammars.ts --from DIR copy from an existing node_modules instead
//   pnpm tsx scripts/vendor-grammars.ts --check    verify the vendored files against the manifest

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface GrammarSource {
  grammar: string;
  file: string;
  package: string;
  version: string;
  /** The .wasm inside the package. */
  path: string;
}

/** The grammars and the exact package versions their .wasm files come from. */
export const GRAMMARS: readonly GrammarSource[] = [
  { grammar: 'javascript', file: 'tree-sitter-javascript.wasm', package: 'tree-sitter-javascript', version: '0.25.0', path: 'tree-sitter-javascript.wasm' },
  { grammar: 'typescript', file: 'tree-sitter-typescript.wasm', package: 'tree-sitter-typescript', version: '0.23.2', path: 'tree-sitter-typescript.wasm' },
  { grammar: 'tsx', file: 'tree-sitter-tsx.wasm', package: 'tree-sitter-typescript', version: '0.23.2', path: 'tree-sitter-tsx.wasm' },
  { grammar: 'python', file: 'tree-sitter-python.wasm', package: 'tree-sitter-python', version: '0.25.0', path: 'tree-sitter-python.wasm' },
  { grammar: 'go', file: 'tree-sitter-go.wasm', package: 'tree-sitter-go', version: '0.25.0', path: 'tree-sitter-go.wasm' },
  { grammar: 'rust', file: 'tree-sitter-rust.wasm', package: 'tree-sitter-rust', version: '0.24.0', path: 'tree-sitter-rust.wasm' },
  { grammar: 'java', file: 'tree-sitter-java.wasm', package: 'tree-sitter-java', version: '0.23.5', path: 'tree-sitter-java.wasm' },
  { grammar: 'kotlin', file: 'tree-sitter-kotlin.wasm', package: '@tree-sitter-grammars/tree-sitter-kotlin', version: '1.1.0', path: 'tree-sitter-kotlin.wasm' },
  { grammar: 'ruby', file: 'tree-sitter-ruby.wasm', package: 'tree-sitter-ruby', version: '0.23.1', path: 'tree-sitter-ruby.wasm' },
];

export const GRAMMAR_DIR = fileURLToPath(new URL('../assets/grammars/', import.meta.url));
export const MANIFEST = join(GRAMMAR_DIR, 'grammars.json');

export interface Manifest {
  note: string;
  runtime: { package: string; version: string };
  grammars: (GrammarSource & { sha256: string; bytes: number; license: string | null })[];
}

const sha256 = (path: string) => createHash('sha256').update(readFileSync(path)).digest('hex');

/** The unpacked package directory for `g`, from `from` (a node_modules) or a fresh `npm pack`. */
function packageDir(g: GrammarSource, from: string | null, scratch: string): string {
  if (from) return join(from, g.package);
  const dest = join(scratch, g.package.replace('/', '__'));
  if (existsSync(join(dest, 'package'))) return join(dest, 'package');
  mkdirSync(dest, { recursive: true });
  // `npm pack` only downloads the tarball: no dependencies are installed and no scripts run.
  const name = execFileSync('npm', ['pack', `${g.package}@${g.version}`, '--ignore-scripts', '--silent', '--pack-destination', dest], { encoding: 'utf8' }).trim().split('\n').pop()!;
  execFileSync('tar', ['-xzf', join(dest, name), '-C', dest]);
  return join(dest, 'package');
}

function vendor(from: string | null): void {
  mkdirSync(join(GRAMMAR_DIR, 'licenses'), { recursive: true });
  const scratch = mkdtempSync(join(tmpdir(), 'grammars-'));
  const runtime = JSON.parse(readFileSync(fileURLToPath(new URL('../package.json', import.meta.url)), 'utf8')).dependencies['web-tree-sitter'] as string;
  const manifest: Manifest = {
    note: 'Generated by scripts/vendor-grammars.ts: the published .wasm of each grammar package, at the version listed. Do not edit by hand.',
    runtime: { package: 'web-tree-sitter', version: runtime },
    grammars: [],
  };
  try {
    for (const g of GRAMMARS) {
      const dir = packageDir(g, from, scratch);
      const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')) as { version: string; license?: string };
      if (pkg.version !== g.version) throw new Error(`${g.package} is ${pkg.version}, expected ${g.version}`);
      const out = join(GRAMMAR_DIR, g.file);
      copyFileSync(join(dir, g.path), out);
      const license = ['LICENSE', 'LICENSE.md', 'LICENSE.txt'].map((f) => join(dir, f)).find(existsSync);
      if (license) copyFileSync(license, join(GRAMMAR_DIR, 'licenses', `${g.package.replace('/', '__')}.txt`));
      manifest.grammars.push({ ...g, sha256: sha256(out), bytes: readFileSync(out).length, license: pkg.license ?? null });
    }
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
  writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  for (const g of manifest.grammars) console.log(`${g.file.padEnd(28)} ${g.package}@${g.version} ${g.sha256.slice(0, 16)}… ${g.bytes} bytes`);
}

/** Problems with the vendored files: each listed grammar present with the recorded sha256. */
export function checkVendored(): string[] {
  const problems: string[] = [];
  if (!existsSync(MANIFEST)) return [`missing ${MANIFEST}`];
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8')) as Manifest;
  for (const g of GRAMMARS) {
    const entry = manifest.grammars.find((m) => m.file === g.file);
    const path = join(GRAMMAR_DIR, g.file);
    if (!entry) problems.push(`${g.file} is not in the manifest`);
    else if (entry.version !== g.version || entry.package !== g.package) problems.push(`${g.file}: manifest says ${entry.package}@${entry.version}`);
    else if (!existsSync(path)) problems.push(`${g.file} is missing`);
    else if (sha256(path) !== entry.sha256) problems.push(`${g.file} does not match its sha256`);
  }
  return problems;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  if (args.includes('--check')) {
    const problems = checkVendored();
    for (const p of problems) console.error(p);
    if (problems.length > 0) process.exit(1);
    console.log(`${GRAMMARS.length} grammars match the manifest`);
  } else {
    const at = args.indexOf('--from');
    vendor(at >= 0 ? args[at + 1]! : null);
  }
}
